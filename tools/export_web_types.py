"""Export what the web viewer needs to know about the save format and the
machine types, as web/types.json.

The web app must not carry a hand-copied second definition of every machine:
that is the "GLSL disagrees with Python" bug class core/glsl_types.py exists to
end. So this walks the real classes and writes their geometry out as data.

Port faces are exported **already placed** for every (direction, flip), using
Entity.faces_at_origin() -- the same function the simulation uses. The web
side therefore does no rotation maths of its own to draw a port, and cannot
get it wrong.

Re-run after any change to core/cell.py or core/entity.py:

    python tools/export_web_types.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from core import cell, entity  # noqa: E402
from core.entity import Entity, Belt, Underground, Source, Structure  # noqa: E402
from core import belts, segments  # noqa: E402


def kind_of(cls):
    if cls is Belt:
        return "belt"
    if cls is Underground:
        return "under"
    return "structure"


def pass_cells(cls, d, flipped, w, h, ins, outs):
    """[(lx, ly, axis)] for the control-signal overlay, in placed space.

    The same rule the desktop shader applies per pixel (world.frag, the
    "control-signal overlay" block): an axis the type declares in
    PASS_THROUGH, flipped then rotated like a port face; drawn on a cell that
    has an output port facing along it, an input port facing back along it,
    or that sits between two cells of the footprint on that axis.
    """
    axes = []
    for a in cls.PASS_THROUGH:
        if flipped:
            a = cell.flip_dir_y(a)
        axes.append(cell.rotate_dir_ccw_n(a, d))
    out = []
    for lx in range(w):
        for ly in range(h):
            for a in axes:
                sx, sy = cell.DIR_STEPS[a]
                back = (a + 2) % 4
                fwd_room = (lx + sx in range(w)) and (ly + sy in range(h)) and (sx or sy)
                back_room = (lx - sx in range(w)) and (ly - sy in range(h)) and (sx or sy)
                on = ((lx, ly), a) in outs or ((lx, ly), back) in ins or (fwd_room and back_room)
                if on:
                    out.append([lx, ly, a])
    return out


def sim_entry(cls):
    """What the web tick needs to fire this type: the rule, the channels, the
    arithmetic as opcodes. All of it read from the class, as glsl_types.py
    reads it for the GPU kernels -- never restated by hand."""
    if kind_of(cls) != "structure":
        return None
    if cls.OPS is None:
        raise SystemExit(f"{cls.__name__} has no OPS table; the web tick cannot fire it")
    return {
        "fire_rule": cls.FIRE_RULE,
        # Port index (the order of `inputs` / `outputs` below) -> channel.
        "in_ch": [cls.in_channel(i) for i in range(len(cls.INPUTS))],
        "out_ch": [cls.out_channel(i) for i in range(len(cls.OUTPUTS))],
        "n_in": cls.in_channels(),
        "n_out": cls.out_channels(),
        "ops": [list(op) for op in cls.OPS],
        "select": list(cls.SELECT_RULE) if cls.SELECT_RULE else None,
    }


def type_entry(cls):
    orient = {}
    for d in range(4):
        for flipped in (False, True):
            w, h = cls.footprint_for(d)
            ins, outs = cls.faces_at_origin(d, flipped)
            orient[f"{d}{int(flipped)}"] = {
                "w": w, "h": h,
                # [local_x, local_y, face_direction], in placed space.
                "inputs": [[x, y, f] for ((x, y), f) in ins],
                "outputs": [[x, y, f] for ((x, y), f) in outs],
                "pass": pass_cells(cls, d, flipped, w, h, set(ins), set(outs)),
            }
    return {
        "name": cell.TYPE_NAMES[cls.TYPE_ID],
        "class": cls.__name__,
        "kind": kind_of(cls),
        "footprint": list(cls.FOOTPRINT),
        "colour": list(cls.COLOUR) if cls.COLOUR else None,
        "chiral": bool(cls.is_chiral()) if kind_of(cls) == "structure" else False,
        "glyph": getattr(cls, "GLYPH", "none"),
        "orient": orient,
        "sim": sim_entry(cls),
    }


def build():
    types = {}
    for type_id, cls in sorted(Entity._registry.items()):
        types[str(type_id)] = type_entry(cls)
    return {
        "_comment": "Generated by tools/export_web_types.py -- do not edit.",
        "cell": {
            "DIR_SHIFT": cell.DIR_SHIFT, "DIR_MASK": cell.DIR_MASK,
            "TYPE_SHIFT": cell.TYPE_SHIFT, "TYPE_MASK": cell.TYPE_MASK,
            "ID_SHIFT": cell.ID_SHIFT, "ID_MASK": cell.ID_MASK,
            "LOCAL_SHIFT": cell.LOCAL_SHIFT, "LOCAL_MASK": cell.LOCAL_MASK,
            "GHOST_MASK": cell.GHOST_MASK,
            "FLIP_BIT": cell.FLIP_BIT,
            "UNDER_EXIT_BIT": cell.UNDER_EXIT_BIT,
            "UNDER_PAIRED_BIT": cell.UNDER_PAIRED_BIT,
            "SEED_BIT": cell.SEED_BIT,
            "SEED_POS_BIT": cell.SEED_POS_BIT,
            "DIR_STEPS": [list(s) for s in cell.DIR_STEPS],
            "TYPE_EMPTY": cell.TYPE_EMPTY,
            "TYPE_BELT": cell.TYPE_BELT,
            "TYPE_UNDER": cell.TYPE_UNDER,
        },
        "entity": {
            "STRIDE": entity.ENTITY_STRIDE,
            "F_ALIVE": Entity.F_ALIVE, "F_TYPE": Entity.F_TYPE,
            "F_ORIGIN_X": Entity.F_ORIGIN_X, "F_ORIGIN_Y": Entity.F_ORIGIN_Y,
            "F_DIR": entity._F_DIR,
            "F_W": Entity.F_W, "F_H": Entity.F_H,
            "F_FLIPPED": Entity.F_FLIPPED,
            "F_EMIT": Source.F_EMIT,
            "F_SEED_ON": Belt.F_SEED_ON, "F_SEED_VALUE": Belt.F_SEED_VALUE,
            "F_UNDER_IS_EXIT": Underground.F_IS_EXIT,
            "F_UNDER_PARTNER": Underground.F_PARTNER,
        },
        "under": {
            # The longest pair: ends at most MAX_SPAN apart, so at most
            # MAX_GAP buried cells between them.
            "MAX_GAP": Underground.MAX_GAP,
            "MAX_SPAN": Underground.MAX_SPAN,
        },
        "sim": {
            "UNIT": belts.UNIT,
            "SPEED": belts.DEFAULT_SPEED,
            "SPACING": belts.DEFAULT_SPACING,
            "MIN_RING_CAP": segments.MIN_RING_CAP,
            "MAX_SEGMENT_LEN": cell.MAX_SEGMENT_LEN,
            "MAX_SEGMENT_ID": cell.MAX_SEGMENT_ID,
            "GHOST_PENDING": cell.GHOST_PENDING,
            "VALUE_LIMIT": entity.VALUE_LIMIT,
            "MAX_CHANNELS": entity.MAX_CHANNELS,
            "F_IN_VALUE": Entity.F_IN_VALUE, "F_IN_HELD": Entity.F_IN_HELD,
            "F_OUT_VALUE": Entity.F_OUT_VALUE, "F_OUT_HELD": Entity.F_OUT_HELD,
            "FIRE_ALL": Structure.FIRE_ALL, "FIRE_ANY": Structure.FIRE_ANY,
            "FIRE_SELECT": Structure.FIRE_SELECT,
            "OPS": {n: getattr(Structure, n) for n in dir(Structure)
                    if n.startswith("OP_")},
        },
        "types": types,
    }


if __name__ == "__main__":
    out = os.path.join(ROOT, "web", "types.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        json.dump(build(), fh, indent=1)
        fh.write("\n")
    print(f"wrote {out}")
